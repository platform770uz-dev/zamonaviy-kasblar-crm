const ATTRS = ["placeholder", "aria-label", "title"];
const SKIP_TAGS = new Set(["SCRIPT", "STYLE", "TEXTAREA", "NOSCRIPT"]);
const textState = new WeakMap(); // текстовый узел -> { ru, uz }
const attrState = new WeakMap(); // элемент -> { атрибут: { ru, uz } }

export function uzText(value) {
  const text = String(value ?? "").trim();
  if (uzPhrases[text]) return uzPhrases[text];
  for (const [pattern, replacement] of uzPatterns) if (pattern.test(text)) return text.replace(pattern, replacement);
  return value;
}

function translateValue(value) {
  const trimmed = value.trim();
  if (!trimmed) return null;
  const translated = uzText(trimmed);
  return translated === trimmed ? null : value.replace(trimmed, () => translated);
}

function translateTextNode(node) {
  const known = textState.get(node);
  if (known) {
    if (node.nodeValue === known.uz) return;
    textState.delete(node);
  }
  const translated = translateValue(node.nodeValue);
  if (translated === null) return;
  textState.set(node, { ru: node.nodeValue, uz: translated });
  node.nodeValue = translated;
}

function translateAttrs(element) {
  for (const name of ATTRS) {
    if (!element.hasAttribute?.(name)) continue;
    const current = element.getAttribute(name);
    const states = attrState.get(element) || {};
    if (states[name] && states[name].uz === current) continue;
    const translated = translateValue(current);
    if (translated === null) continue;
    states[name] = { ru: current, uz: translated };
    attrState.set(element, states);
    element.setAttribute(name, translated);
  }
}

function eachTextNode(root, callback) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode: (node) => (node.parentElement && SKIP_TAGS.has(node.parentElement.tagName) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT),
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach(callback);
}

export function translateTree(root) {
  if (root.nodeType === Node.TEXT_NODE) { translateTextNode(root); return; }
  if (root.nodeType !== Node.ELEMENT_NODE) return;
  eachTextNode(root, translateTextNode);
  translateAttrs(root);
  root.querySelectorAll("[placeholder],[aria-label],[title]").forEach(translateAttrs);
}

export function restoreTree(root) {
  eachTextNode(root, (node) => {
    const known = textState.get(node);
    if (known && node.nodeValue === known.uz) node.nodeValue = known.ru;
    textState.delete(node);
  });
  root.querySelectorAll("[placeholder],[aria-label],[title]").forEach((element) => {
    const states = attrState.get(element);
    if (!states) return;
    for (const [name, value] of Object.entries(states)) if (element.getAttribute(name) === value.uz) element.setAttribute(name, value.ru);
    attrState.delete(element);
  });
}

export function startUzObserver(isActive) {
  const observer = new MutationObserver((mutations) => {
    if (!isActive()) return;
    for (const mutation of mutations) {
      if (mutation.type === "characterData") translateTextNode(mutation.target);
      else mutation.addedNodes.forEach(translateTree);
    }
  });
  observer.observe(document.body, { childList: true, subtree: true, characterData: true });
}
